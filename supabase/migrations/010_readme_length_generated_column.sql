-- Migration 010: servers.readme_length — a generated, stored README length.
--
-- WHY
-- ---
-- isIndexable() (apps/web/lib/indexable.ts) scores a server on 5 signals, one
-- of which is "README present and substantial": trim(readme_content) >= 400
-- characters. Every query that evaluates that predicate over a large row set
-- therefore had to SELECT readme_content itself — the sitemap scan
-- (_getIndexableSitemapRows), the generateStaticParams scan
-- (getIndexableServerSlugs), the gated top-N and gated category scans.
--
-- Those routes are force-dynamic and scan the whole `servers` table. Today
-- readme_content is NULL on ~97.8% of rows, so the transfer is only ~7 MB. A
-- repaired GitHub enrichment backfill changes that: ~21k enrichable rows at a
-- sampled mean of ~12.0 KB per README is ~250 MB pulled per request, plus the
-- TOAST detoasting to produce it, on an instance already swapping. Repairing
-- enrichment was blocked on this.
--
-- A STORED generated column moves the length into the heap tuple: 4 bytes per
-- row, and a SELECT that never names readme_content never detoasts it.
--
-- WHY GENERATED RATHER THAN SYNC-MAINTAINED
-- -----------------------------------------
-- readme_content is written by packages/sync/src/github-enrichment.ts. A
-- plain column maintained by that writer can drift the moment any other
-- writer (a backfill script, a manual UPDATE, a future enrichment path)
-- touches readme_content and forgets the length. GENERATED ALWAYS makes
-- drift unrepresentable — Postgres recomputes it on every INSERT and UPDATE
-- and refuses direct writes.
--
-- WHY NOT A VIEW OR AN RPC
-- ------------------------
-- A view computing length(btrim(readme_content)) still has to read and
-- detoast every README on every scan, which is the actual cost being removed
-- here. An RPC that evaluates the whole eligibility rule server-side would
-- reimplement isIndexable() in SQL — a second copy of the predicate in a
-- second language, which is precisely the drift class lib/indexable.ts's own
-- docblock exists to forbid.
--
-- SEMANTICS
-- ---------
-- The expression mirrors the JS it replaces: content.trim().length.
--   - btrim(x, E' \t\n\r\f\v ') removes the whitespace JS String.trim()
--     removes, for every whitespace character that occurs in practice.
--   - length() on text counts characters. JS .length counts UTF-16 code
--     units, so a character outside the BMP (an emoji) counts 1 here and 2
--     there. The two answers can only disagree about indexability for a
--     README whose trimmed length sits within a couple of characters of the
--     400 boundary AND that carries astral-plane characters near that
--     boundary. See scripts/verify-readme-length-parity.mjs — run it AFTER
--     applying this migration to prove the eligible count (478 at the time of
--     writing) is unchanged before trusting the new column.
--   - NULL readme_content yields NULL readme_length, which isIndexable()
--     scores exactly as the old `readme_content == null` branch did.
--
-- APPLYING
-- --------
-- Applied to the production mcp-find project on 2026-09-11 through the linked
-- Supabase CLI. The pre-apply JS signal count and post-apply generated-column
-- count both returned 1,429 active rows; the boundary parity check inspected
-- 3 rows and found 0 eligibility disagreements. IF NOT EXISTS keeps reruns safe.
--
-- Deploy order is NOT load-bearing: apps/web/lib/queries.ts probes for this
-- column and falls back to selecting readme_content (the old behaviour, and
-- the old cost) when it is absent, so the app is correct whether this
-- migration lands before or after the code.

ALTER TABLE servers
  ADD COLUMN IF NOT EXISTS readme_length integer
  GENERATED ALWAYS AS (length(btrim(readme_content, E' \t\n\r\f\v '))) STORED;

COMMENT ON COLUMN servers.readme_length IS
  'Trimmed character length of readme_content, generated by Postgres. Read by isIndexable() so the sitemap and static-params scans never transfer README bodies. Never write this directly.';
